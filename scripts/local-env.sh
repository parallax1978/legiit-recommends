#!/usr/bin/env bash
# Writes .env.local for local development from the running local Supabase stack.
set -euo pipefail
cd "$(dirname "$0")/.."

status="$(npx supabase status -o env 2>/dev/null)" || {
  echo "The local Supabase stack is not running. Start it with: npm run db:start" >&2
  exit 1
}
value() { printf '%s\n' "$status" | grep "^$1=" | head -1 | cut -d= -f2- | tr -d '"'; }

api_url="$(value API_URL)"
publishable="$(value PUBLISHABLE_KEY)"
secret="$(value SECRET_KEY)"
[ -n "$publishable" ] || publishable="$(value ANON_KEY)"
[ -n "$secret" ] || secret="$(value SERVICE_ROLE_KEY)"

worker_secret="local-dev-worker-secret-change-me-0000"
if [ -f supabase/functions/.env ]; then
  from_file="$(grep '^WORKER_SECRET=' supabase/functions/.env | head -1 | cut -d= -f2- || true)"
  [ -n "$from_file" ] && worker_secret="$from_file"
else
  cp supabase/functions/.env.example supabase/functions/.env
fi

umask 077
cat > .env.local <<ENV
# Generated by scripts/local-env.sh for the LOCAL Supabase stack. Do not commit.
# Web app: public values only. The web app never holds a service key.
NEXT_PUBLIC_SUPABASE_URL=$api_url
NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=$publishable
ENV
cat > .env.operator <<ENV
# Generated by scripts/local-env.sh for the LOCAL Supabase stack. Do not commit.
# Operator scripts only (bootstrap:owner, queues:activate). Not read by Next.js.
SUPABASE_URL=$api_url
SUPABASE_SECRET_KEY=$secret
SITE_URL=http://localhost:3000
WORKER_SECRET=$worker_secret
ENV
echo "Wrote .env.local (web) and .env.operator (scripts) for $api_url"
